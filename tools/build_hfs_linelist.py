"""Build ``src/species/data/linelists/hfs_mn_cu.dat`` from published HFS line lists.

This is the provenance record for the hyperfine-structure table, not part of
the package. It needs ``h5py`` and two inputs that are not in the repository:

* the Gaia-ESO line list of Heiter et al. (2021, A&A 645, A106) in the HDF5
  form Korg distributes (``Heiter_et_al_2021.h5``, Korg artifact
  ``Heiter_2021_GES_linelist``, air wavelengths), and
* Kurucz's hyperfine line lists ``hyper250055.dat`` (Mn I) and
  ``hyper290063.dat`` / ``hyper290065.dat`` (63Cu I, 65Cu I) from
  http://kurucz.harvard.edu/linelists/gfhyperall/, used only for lines the
  Gaia-ESO list gives unsplit.

For every Mn I and Cu I line in ``lines_ab.dat`` the components are those of the
same species and lower level (|dEP| < 0.02 eV) within 0.15 A. Only the *shape*
of the pattern is taken from the source: the relative strengths
``gf_i / sum(gf)`` and the offsets from the gf-weighted centroid. The total
log gf and the centroid wavelength stay those of ``lines_ab.dat``, so the
components of each line sum exactly to the gf the rest of the line list uses.

Usage::

    python tools/build_hfs_linelist.py GES.h5 KURUCZ_DIR > src/species/data/linelists/hfs_mn_cu.dat
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

CM_TO_EV = 1.239841984e-4
WINDOW = 0.15  # A
DEP = 0.02  # eV

ELEMENTS = {25.0: ("Mn I", ["hyper250055.dat"]), 29.0: ("Cu I", ["hyper290063.dat", "hyper290065.dat"])}


def read_lines_ab(path: Path) -> list[tuple[float, float, float, float]]:
    rows = []
    for line in path.read_text().splitlines()[2:]:
        parts = line.split()
        if len(parts) < 5:
            continue
        wl, ep, gf, ion = float(parts[0]), float(parts[1]), float(parts[2]), float(parts[4])
        if ion in ELEMENTS:
            rows.append((wl, ep, gf, ion))
    return rows


def ges_components(h5, wl0: float, ep0: float, species: str) -> list[tuple[float, float]]:
    wl = h5["wl"]
    i0, i1 = np.searchsorted(wl[:], [wl0 - WINDOW, wl0 + WINDOW])
    sp = [s.decode() for s in h5["species"][i0:i1]]
    w = wl[i0:i1]
    gf = h5["log_gf"][i0:i1]
    ep = h5["E_lower"][i0:i1]
    return [
        (float(w[k]), float(gf[k]))
        for k in range(len(sp))
        if sp[k] == species and abs(ep[k] - ep0) < DEP
    ]


def kurucz_components(files: list[Path], wl0: float, ep0: float, code: str):
    out = []
    for f in files:
        for line in f.read_text().splitlines():
            if len(line) < 124 or line[18:24].strip() != code:
                continue
            wl = float(line[0:11]) * 10.0  # nm -> A (air above 200 nm)
            if abs(wl - wl0) > WINDOW:
                continue
            e_lo = min(abs(float(line[24:36])), abs(float(line[52:64]))) * CM_TO_EV
            if abs(e_lo - ep0) > DEP:
                continue
            # log fraction of the hyperfine component plus log isotope fraction
            rel = float(line[109:115]) + float(line[118:124])
            out.append((wl, rel))
    return out


def main() -> int:
    import h5py

    ges_path, kurucz_dir = Path(sys.argv[1]), Path(sys.argv[2])
    repo = Path(__file__).resolve().parents[1]
    parents = read_lines_ab(repo / "src/species/data/linelists/lines_ab.dat")

    print("# Hyperfine-structure (and, for Cu, isotopic) components of the Mn I and Cu I")
    print("# lines in lines_ab.dat, for MOOG's `blends` driver.")
    print("#")
    print("# Pattern sources (relative strengths and wavelength offsets only):")
    print("#   GES    Gaia-ESO line list v6, Heiter et al. 2021, A&A 645, A106")
    print("#          (Korg artifact Heiter_2021_GES_linelist, file Heiter_et_al_2021.h5)")
    print("#   KURUCZ Kurucz gfhyperall hyper250055.dat (Mn I), hyper290063/065.dat (Cu I)")
    print("#          http://kurucz.harvard.edu/linelists/gfhyperall/ (lines GES gives unsplit)")
    print("# Each line keeps the total log gf and the air wavelength of lines_ab.dat:")
    print("#   comp_wl  = parent_wl + (src_wl_i - src_centroid_gf_weighted)")
    print("#   comp_lgf = parent_loggf + log10(gf_i / sum gf)")
    print("# so sum(10**comp_lgf) == 10**parent_loggf for every parent line.")
    print("# Generated by tools/build_hfs_linelist.py.")
    print("#")
    print("# parent_wl  comp_wl    EP     comp_lgf  ion   source")

    with h5py.File(ges_path, "r") as h5:
        for wl0, ep0, gf0, ion in parents:
            species, kfiles = ELEMENTS[ion]
            comps = ges_components(h5, wl0, ep0, species)
            source = "GES"
            if len(comps) < 2:
                code = f"{ion:.2f}"
                comps = kurucz_components([kurucz_dir / f for f in kfiles], wl0, ep0, code)
                source = "KURUCZ"
            if len(comps) < 2:
                print(f"no HFS pattern found for {species} {wl0}", file=sys.stderr)
                return 1
            w = np.array([c[0] for c in comps])
            g = 10.0 ** np.array([c[1] for c in comps])
            frac = g / g.sum()
            centroid = float(np.sum(frac * w))
            if abs(centroid - wl0) > 0.05:
                print(f"{species} {wl0}: source centroid {centroid:.4f} far off", file=sys.stderr)
                return 1
            order = np.argsort(w)
            for k in order:
                print(
                    f"{wl0:9.3f}  {wl0 + (w[k] - centroid):9.4f}  {ep0:5.3f}  "
                    f"{gf0 + np.log10(frac[k]):8.4f}  {ion:4.1f}  {source}"
                )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
